  points(text, x, y, scale) {
    const result = [];
    [...text.toUpperCase()].forEach((char, i) => {
      const rows = (this.glyphs[char] || '').split('/');
      rows.forEach((row, r) => [...row].forEach((bit, c) => { if (bit === '1') result.push(createVector(x + (i * 6 + c) * scale, y + r * scale)); }));
    });
    return result;
  },
  isFormed(cache, ids, tolerance = 8) {
    const entries = [...ids].map(id => cache[id]).filter(Boolean);
    return entries.length > 0 && entries.every(entry => entry.pixels.every(pixel => Math.hypot(pixel.pos.x-pixel.target.x,pixel.pos.y-pixel.target.y)<=tolerance));
  },
  set(cache, id, text, x, y, scale, color = '#dceadd', forming = true, bounds = { x:0, y:0, w:width, h:height }, mouse = null) {
    const signature = [text, x, y, scale, color].join('|');
    if (cache[id]?.signature !== signature) {
      const previous = cache[id]?.pixels || [];
      const pixels = this.points(text, x, y, scale).map((target, i) => {
        const scatter = createVector(random(bounds.x + 18, bounds.x + bounds.w - 18), random(bounds.y + 18, bounds.y + bounds.h - 18));
        const pixel = previous[i] || new TextPixel(scatter.x, scatter.y, target, scatter, color, scale * 0.76);
        pixel.target = target; pixel.color = color; pixel.size = scale * 0.76; return pixel;
      });
      cache[id] = { signature, pixels };
    }
    for (const pixel of cache[id].pixels) { pixel.step(forming, millis()/1000, mouse); pixel.show(); }
  }
